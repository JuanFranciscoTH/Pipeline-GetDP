"""run.py -- pipeline driver.

    block CSV + config.yaml
      -> coil placed on the rock (z computed)        environment.py
      -> Gmsh mesh model.msh (air / coil / rock)     mesh_builder.py
      -> data.pro (regions, sigma, mu_r, source)     this file
      -> GetDP harmonic solve -> results/b.pos       formulation.pro
      -> results/B_field.vtu                         export_vtu.py
      -> report: |B| at the coil centre vs Biot-Savart + the markers table

Usage:
    python run.py               # full run (mesh + solve + B_field.vtu + report)
    python run.py --mesh-only   # build model.msh and stop (check its size first)
"""
from __future__ import annotations

import argparse
import json
import math
import os
import re
import shutil
import subprocess
import time

import common
import environment
import export_vtu
import mesh_builder

MESH = "model.msh"
FORMULATION = "formulation.pro"
DATA_PRO = "data.pro"
GETDP_LOG = "getdp.log"


def log(msg: str) -> None:
    print(f"[run] {msg}", flush=True)


def mumps_memory_gb(n_tets: int, arithmetic: str) -> float:
    """Rough peak memory of the GetDP/MUMPS solve, fitted on meshes of this model
    (conservative by ~5 %):
      'real'    PETSc built for real numbers (Ubuntu package, GetDP 3.2.0): the
                complex system is solved as a real one of twice the size
                -> 391,714 tets ~ 11.5 GB;
      'complex' PETSc built for complex numbers (official binaries, GetDP 3.5.0
                on Windows) -> half of that, 391,714 tets ~ 6.0 GB."""
    real = 9.46e-8 * n_tets ** 1.45
    return real if arithmetic == "real" else 0.5 * real


def getdp_command(scfg: dict, args: list) -> list:
    """Command line that runs GetDP with `args` in the project folder: inside WSL
    (Windows with solver.use_wsl) or the native executable solver.getdp."""
    getdp = str(scfg.get("getdp", "getdp"))
    if os.name == "nt" and scfg.get("use_wsl", True):
        wsl = shutil.which("wsl")
        if not wsl:
            raise SystemExit("solver.use_wsl is true but 'wsl' was not found (is WSL installed?)")
        here = os.path.abspath(".")
        wsl_dir = f"/mnt/{here[0].lower()}" + here[2:].replace("\\", "/")
        inner = (f"ulimit -s unlimited 2>/dev/null; export OMP_STACKSIZE=1g; "
                 f"cd '{wsl_dir}' && {getdp} {' '.join(args)}")
        return [wsl, "-d", str(scfg.get("wsl_distro", "Ubuntu-24.04")), "--", "bash", "-lc", inner]
    exe = shutil.which(getdp) or (getdp if os.path.isfile(getdp) else None)
    if not exe:
        raise SystemExit(f"GetDP executable {getdp!r} not found (config.yaml -> solver.getdp)")
    return [exe] + args


def getdp_arithmetic(scfg: dict) -> str | None:
    """'complex' or 'real': the PETSc build of the configured GetDP (`getdp -info`).
    None if it cannot be determined."""
    try:
        res = subprocess.run(getdp_command(scfg, ["-info"]), capture_output=True, text=True,
                             errors="replace", timeout=120)
    except (OSError, subprocess.SubprocessError, SystemExit):
        return None
    out = (res.stdout or "") + (res.stderr or "")      # GetDP prints -info on stderr
    m = re.search(r"\((complex|real) arithmetic\)", out)
    return m.group(1) if m else None


def write_data_pro(info, coil: dict, coil_center) -> None:
    """data.pro: everything case-dependent that formulation.pro needs."""
    cond = [c for c in info.rock_classes if c[1] > 0.0]
    insul = [c for c in info.rock_classes if c[1] <= 0.0]

    def region(tags):
        return "Region[{" + ", ".join(str(t) for t in tags) + "}]"

    ni = float(coil["turns"]) * float(coil["current"])
    L = ["// AUTO-GENERATED by run.py from config.yaml and the block CSV -- do not edit.",
         "Group {",
         f"  Air         = Region[{mesh_builder.AIR_TAG}];",
         f"  Coil        = Region[{mesh_builder.COIL_TAG}];",
         f"  Sur_Outer   = Region[{mesh_builder.OUTER_TAG}];",
         f"  DomainC     = {region(c[0] for c in cond)};   // conducting rock classes",
         f"  DomainI     = {region(c[0] for c in insul)};   // rock with sigma = 0",
         "  DomainS     = Region[{Coil}];",
         "  Domain      = Region[{Air, Coil, DomainI, DomainC}];",
         "  DomainGauge = Region[{Air, Coil, DomainI}];",
         "}",
         "Function {",
         "  mur[Air]  = 1.;  epsr[Air]  = 1.;",
         "  mur[Coil] = 1.;  epsr[Coil] = 1.;"]
    for tag, sig, mu, eps, n in info.rock_classes:
        L.append(f"  mur[Region[{tag}]] = {mu:.6g};  epsr[Region[{tag}]] = {eps:.6g};"
                 + (f"  sigma[Region[{tag}]] = {sig:.6e};" if sig > 0 else "")
                 + f"   // {n} tets")
    if not cond:
        L.append("  sigma[Air] = 0.;   // no conducting rock: keeps the formulation valid")
    L += ["}",
          f"Rmin_coil = {float(coil['minor_radius']):.10g};",
          f"NI_coil   = {ni:.10g};",
          f"Cx = {coil_center[0]:.10g}; Cy = {coil_center[1]:.10g};",
          f"Freq_Hz   = {float(coil['frequency']):.10g};", ""]
    with open(DATA_PRO, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(L))
    eps = [c[3] for c in cond]
    log(f"{DATA_PRO}: {len(cond)} conducting rock classes"
        + (f" (eps_r {min(eps):g}..{max(eps):g})" if eps else "")
        + f", {len(insul)} with sigma = 0; N*I = {ni:g} A-turns, "
          f"f = {float(coil['frequency']):g} Hz")
    if insul:
        log(f"note: the {len(insul)} rock classes with sigma = 0 are treated as insulators "
            "(gauged): their eps_r is not used")


def run_getdp(scfg: dict) -> None:
    """Run GetDP in the project folder: inside WSL (Windows with solver.use_wsl)
    or the native executable solver.getdp (Linux, or Windows without WSL).
    The output is shown live and saved to getdp.log."""
    cmd = getdp_command(scfg, [FORMULATION, "-msh", MESH, "-solve", "Dyn", "-v", "4"])
    log("$ " + " ".join(cmd))
    t0 = time.time()
    with open(GETDP_LOG, "w", encoding="utf-8", errors="replace") as fh:
        p = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                             text=True, errors="replace",
                             env=dict(os.environ, OMP_STACKSIZE="1g"))
        for line in p.stdout:
            fh.write(line); print("  " + line.rstrip(), flush=True)
        p.wait()
    if p.returncode != 0:
        raise SystemExit(f"GetDP failed (exit code {p.returncode}) -- see {GETDP_LOG}")
    log(f"GetDP finished in {(time.time() - t0) / 60:.1f} min")


def report(cfg: dict, env, info: dict) -> None:
    """|B| at the coil centre vs the free-space Biot-Savart value + markers."""
    import numpy as np
    import pyvista as pv
    mesh = common.read_field()
    c = info["coil_center"]
    b0 = float(np.asarray(pv.PolyData(np.array([c], float)).sample(mesh)["Bamp"])[0])
    biot = 4e-7 * math.pi * info["NI"] / (2.0 * info["major_radius"])
    log(f"|B| at the coil centre ({c[0]:g}, {c[1]:g}, {c[2]:g}) = {b0:.3e} T; "
        f"free-space Biot-Savart = {biot:.3e} T (ratio {b0 / biot:.3f})")
    common.print_markers(common.sample_markers(cfg, mesh, env),
                         csv_path=os.path.join(common.RESULTS, "markers_B.csv"))


def main() -> int:
    ap = argparse.ArgumentParser(description="TX coil over the mine block model: mesh + GetDP")
    ap.add_argument("--mesh-only", action="store_true", help="build model.msh and stop")
    args = ap.parse_args()

    cfg = common.load_config()
    os.makedirs(common.RESULTS, exist_ok=True)
    coil = cfg["coil"]
    env = environment.load(cfg)

    # ---- coil placement --------------------------------------------------
    cx, cy = (float(v) for v in coil["center_xy"])
    R, r = float(coil["major_radius"]), float(coil["minor_radius"])
    z_coil, z_rock, _ = environment.coil_z_on_rock(env, cx, cy, R, r)
    i, j, k = env.index(cx, cy, z_rock - env.dz / 2)
    log(f"coil at (x={cx:g}, y={cy:g}, z={z_coil:g}) m, resting on the rock top z={z_rock:g} m; "
        f"block under it: sigma = {env.sigma[i, j, k]:.4g} S/m, mu_r = {env.mu_r[i, j, k]:g}, "
        f"eps_r = {env.eps_r[i, j, k]:g}")
    log(f"air above the coil: {env.bounds[5] - z_coil:g} m;  rock below it: "
        f"{z_coil - env.bounds[2]:g} m")
    info = {"coil_center": [cx, cy, z_coil], "major_radius": R, "minor_radius": r,
            "NI": float(coil["turns"]) * float(coil["current"]),
            "frequency": float(coil["frequency"]), "csv": env.csv}
    with open(common.RUN_INFO, "w", encoding="utf-8") as fh:
        json.dump(info, fh, indent=2)

    # ---- mesh -----------------------------------------------------------------
    log("building the mesh with Gmsh (a few minutes) ...")
    t0 = time.time()
    minfo = mesh_builder.build_mesh(env, coil, cfg["mesh"], z_coil, MESH)
    n_rock = sum(c[4] for c in minfo.rock_classes)
    log(f"mesh {MESH}: {minfo.n_nodes:,} nodes, {minfo.n_tets:,} tets ({n_rock:,} in rock, "
        f"{len(minfo.rock_classes)} material classes) in {(time.time() - t0) / 60:.1f} min")
    arith = getdp_arithmetic(cfg["solver"])
    if arith:
        log(f"estimated GetDP/MUMPS memory: ~{mumps_memory_gb(minfo.n_tets, arith):.1f} GB "
            f"(GetDP with {arith}-arithmetic PETSc)")
    else:
        log(f"estimated GetDP/MUMPS memory: ~{mumps_memory_gb(minfo.n_tets, 'complex'):.1f} GB "
            f"(complex-arithmetic GetDP, e.g. official binaries) or "
            f"~{mumps_memory_gb(minfo.n_tets, 'real'):.1f} GB (real-arithmetic, e.g. Ubuntu "
            f"package); GetDP not found to tell which")
    if args.mesh_only:
        log("--mesh-only: stopping here (view it with: python view_mesh.py)")
        return 0

    # ---- solve + conversion + report --------------------------------------------
    write_data_pro(minfo, coil, info["coil_center"])
    log("running GetDP (harmonic solve, MUMPS) ...")
    run_getdp(cfg["solver"])
    export_vtu.convert()
    report(cfg, env, info)
    log("pipeline complete -> results/   (next: python view_field.py, python view_snr.py)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
